def 改表(路径, 标签, 值):
    """把表格里以 <标签> 开头的那一行的第二格改成 <值>（None 表示清空）。"""
    t = io.open(路径, encoding='utf-8').read()
    out = []
    for l in t.split('\n'):
        if l.strip().startswith('|'):
            c = l.strip().strip('|').split('|')
            if c and c[0].replace('*', '').strip().startswith(标签) and len(c) >= 2:
                c[1] = ' %s ' % (值 if 值 is not None else '')
                l = '|' + '|'.join(c) + '|'
        out.append(l)
    io.open(路径, 'w', encoding='utf-8').write('\n'.join(out))


